import { mkdirSync, statSync } from 'node:fs';
import { join } from 'node:path';
import { randomUUID } from 'node:crypto';
import XLSX from 'xlsx';
import {
  Document,
  HeadingLevel,
  Packer,
  Paragraph,
  TextRun,
} from 'docx';
import { createRequire } from 'node:module';
import { aegisRootDir } from './harness.js';

// Real office documents, generated locally. The agent (chat or voice) asks for
// a spreadsheet, a Word document or a deck; the file is written into the
// Aegis data folder and served back through /api/documents/<name> so it can be
// opened or downloaded without leaving the app.

export type DocumentKind = 'xlsx' | 'docx' | 'pptx';

export interface DocumentSpec {
  kind: DocumentKind;
  filename?: string;
  title?: string;
  /** Spreadsheet sheets: each row is an array of cell values. */
  sheets?: { name?: string; rows: (string | number | boolean | null)[][] }[];
  /** Document paragraphs (docx). */
  paragraphs?: string[];
  /** Slides (pptx). */
  slides?: { title?: string; bullets?: string[]; notes?: string }[];
}

export interface CreatedDocument {
  kind: DocumentKind;
  name: string;
  path: string;
  downloadUrl: string;
  bytes: number;
}

const EXTENSIONS: Record<DocumentKind, string> = {
  xlsx: 'xlsx',
  docx: 'docx',
  pptx: 'pptx',
};

function safeName(spec: DocumentSpec): string {
  const base = (spec.filename || spec.title || `${spec.kind}-${Date.now()}`)
    .replace(/[\\/:*?"<>|]+/g, '-')
    .replace(/\s+/g, ' ')
    .trim()
    .slice(0, 80);
  const ext = EXTENSIONS[spec.kind];
  const stem = base.toLowerCase().endsWith(`.${ext}`)
    ? base.slice(0, -(ext.length + 1))
    : base;
  return `${stem || 'aegis-document'}-${randomUUID().slice(0, 8)}.${ext}`;
}

export function generatedDir() {
  const dir = join(aegisRootDir(), '.aegis-data', 'generated');
  mkdirSync(dir, { recursive: true });
  return dir;
}

function rowsOf(sheet: {
  rows: (string | number | boolean | null)[][];
}): (string | number | boolean | null)[][] {
  return Array.isArray(sheet.rows) ? sheet.rows : [];
}

async function writeXlsx(spec: DocumentSpec, path: string) {
  const book = XLSX.utils.book_new();
  const sheets = spec.sheets?.length ? spec.sheets : [{ name: 'Sheet1', rows: [] as (string | number | boolean | null)[][] }];
  sheets.forEach((sheet, index) => {
    const worksheet = XLSX.utils.aoa_to_sheet(rowsOf(sheet));
    const rows = rowsOf(sheet);
    const columns = Math.max(0, ...rows.map((row) => row.length));
    worksheet['!cols'] = Array.from({ length: columns }, (_, column) => {
      const widest = rows.reduce((width, row) => Math.max(width, String(row[column] ?? '').length), 8);
      return { wch: Math.max(10, Math.min(48, widest + 2)) };
    });
    if (rows.length > 1 && columns > 0) {
      worksheet['!autofilter'] = { ref: XLSX.utils.encode_range({ s: { r: 0, c: 0 }, e: { r: rows.length - 1, c: columns - 1 } }) };
    }
    const name = (sheet.name || `Sheet${index + 1}`).slice(0, 31);
    XLSX.utils.book_append_sheet(book, worksheet, name);
  });
  XLSX.writeFile(book, path);
}

async function writeDocx(spec: DocumentSpec, path: string) {
  const paragraphs = spec.paragraphs?.length
    ? spec.paragraphs
    : [spec.title ?? 'Aegis document'];
  const children = [
    ...(spec.title
      ? [
          new Paragraph({
            text: spec.title,
            heading: HeadingLevel.HEADING_1,
          }),
        ]
      : []),
    ...paragraphs.map(
      (text) =>
        new Paragraph({
          children: [new TextRun({ text, size: 24 })],
          spacing: { after: 160 },
        }),
    ),
  ];
  const document = new Document({ sections: [{ children }] });
  const buffer = await Packer.toBuffer(document);
  const { writeFileSync } = await import('node:fs');
  writeFileSync(path, buffer);
}

type Deck = {
  layout: string;
  addSlide: () => {
    addText: (text: unknown, options: Record<string, unknown>) => void;
  };
  writeFile: (options: { fileName: string }) => Promise<unknown>;
};

async function writePptx(spec: DocumentSpec, path: string) {
  const require = createRequire(import.meta.url);
  const PptxGenJS = require('pptxgenjs') as new () => Deck;
  const deck = new PptxGenJS();
  deck.layout = 'LAYOUT_WIDE';
  const slides = spec.slides?.length
    ? spec.slides
    : [{ title: spec.title ?? 'Aegis deck', bullets: ['Generated by Aegis'] }];
  for (const slide of slides) {
    const page = deck.addSlide();
    if (slide.title) {
      page.addText(slide.title, {
        x: 0.6,
        y: 0.4,
        w: 12,
        h: 0.9,
        fontSize: 30,
        bold: true,
        color: '1F2937',
      });
    }
    const bullets = slide.bullets ?? [];
    if (bullets.length) {
      page.addText(
        bullets.map((line) => ({ text: line, options: { bullet: true } })),
        {
          x: 0.8,
          y: 1.6,
          w: 11.6,
          h: 5,
          fontSize: 18,
          color: '374151',
          breakLine: true,
        },
      );
    }
  }
  await deck.writeFile({ fileName: path });
}

export async function createDocument(
  spec: DocumentSpec,
): Promise<CreatedDocument> {
  if (!Object.hasOwn(EXTENSIONS, spec.kind))
    throw new Error('Unsupported document kind (use xlsx, docx or pptx).');
  const name = safeName(spec);
  const path = join(generatedDir(), name);
  if (spec.kind === 'xlsx') await writeXlsx(spec, path);
  else if (spec.kind === 'docx') await writeDocx(spec, path);
  else await writePptx(spec, path);
  return {
    kind: spec.kind,
    name,
    path,
    downloadUrl: `/api/documents/${encodeURIComponent(name)}`,
    bytes: statSync(path).size,
  };
}
