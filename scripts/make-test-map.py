lines = []
lines.append("# Aegis agent use-case test map\n")
lines.append(
    "Acceptance and regression map for the Aegis desktop agent. Every case is tool-agnostic: "
    "the agent must choose browser, computer, shell, document, memory or subagent tools itself. "
    "Cases marked **TOP-5** are the hardest and are executed by the agent, not by hand.\n"
)
lines.append("Legend: difficulty = easy / medium / hard.\n")
lines.append("## Top 5 hardest cases (agent-executed)\n")
lines.append("| ID | Case | Why it is hard |\n| --- | --- | --- |")
for cid, name, why in TOP5:
    lines.append(f"| {cid} | {name} | {why} |")
lines.append("\n---\n")

total = 0
top = {cid for cid, _, _ in TOP5}
for section, prefix, cases in SECTIONS:
    lines.append(f"## {section}\n")
    lines.append("| ID | Case | Steps | Expected | Difficulty |\n| --- | --- | --- | --- | --- |")
    for index, (title, steps, expected, difficulty) in enumerate(cases, 1):
        total += 1
        cid = f"{prefix}{index:02d}"
        mark = " **TOP-5**" if cid in top else ""
        lines.append(f"| {cid} | {title}{mark} | {steps} | {expected} | {difficulty} |")
    lines.append("")

lines.append("---\n")
lines.append(f"Total cases: **{total}**.\n")
lines.append("## How to run\n")
lines.append(
    "1. Open Aegis with the computer service started and the permissions the case needs.\n"
    "2. Send the case's steps as one message; never name tools.\n"
    "3. Judge only on tool evidence and artefacts (files, screenshots, links), never narration.\n"
    "4. Record pass / fail / blocked with the run trace id.\n"
    "5. TOP-5 cases are driven by the agent runner (`scripts/agent-cases.mjs`), not by a human.\n"
)

target = os.path.join(os.path.dirname(os.path.dirname(os.path.abspath(__file__))), "docs", "agentic-test-cases.md")
os.makedirs(os.path.dirname(target), exist_ok=True)
io.open(target, "w", encoding="utf-8", newline="\n").write("\n".join(lines))
print(f"wrote {target} with {total} cases")
